"""Re-evaluate all DeepMIMO checkpoints on a cross-BS test set.

Loads each saved checkpoint (under outputs/checkpoints/dm_*) and runs it on
the BS-18 test set generated by tools/prepare_deepmimo_cross_bs_test.py.

Reports per-(model, cr) NMSE on the cross-BS test set, to show generalization
when train and test UEs are NOT spatially correlated (no dense-grid leakage).
"""
from __future__ import annotations

import argparse
import glob
import os
import re
import sys

import numpy as np
import torch
import inspect


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--test-npz',
                    default='/home/ubuntu/Documents/dataset/DeepMIMO_O1_3p4/deepmimo_o1_3p4_bs18_test.npz')
    ap.add_argument('--ckpt-dir',
                    default='/home/ubuntu/Documents/project/DCRNet-V2/outputs/checkpoints')
    ap.add_argument('--batch-size', type=int, default=256)
    ap.add_argument('--gpu', type=str, default='0')
    ap.add_argument('--include', type=str, default='dm_',
                    help='substring filter on checkpoint filename')
    ap.add_argument('--exclude', type=str, default=None,
                    help='substring filter to exclude (e.g. "lr2em4" duplicates)')
    args = ap.parse_args()

    os.environ['CUDA_VISIBLE_DEVICES'] = args.gpu
    device = 'cuda' if torch.cuda.is_available() else 'cpu'
    sys.path.insert(0, '/home/ubuntu/Documents/project/DCRNet-V2')
    import models as M

    # ----- load BS-18 test data -----
    z = np.load(args.test_npz, allow_pickle=True)
    x_te = torch.from_numpy(z['x_test']).to(device)
    n_test = len(x_te)
    print(f'loaded {args.test_npz}  test shape={tuple(x_te.shape)}')

    # ----- discover checkpoints -----
    paths = sorted(glob.glob(os.path.join(args.ckpt_dir, '*')))
    paths = [p for p in paths if args.include in os.path.basename(p)]
    if args.exclude:
        paths = [p for p in paths if args.exclude not in os.path.basename(p)]
    print(f'found {len(paths)} checkpoints')

    # Parse: <model>-<exp>X-cr<cr>-<scenario>-<tag>
    name_re = re.compile(r'^([a-z0-9]+)-(\d+)X-cr(\d+)-([a-z]+)-(.+)$')

    results = []  # (model_id, cr, tag, nmse_dB)
    for p in paths:
        base = os.path.basename(p)
        m = name_re.match(base)
        if not m:
            print(f'  skip (unparseable): {base}')
            continue
        model_id, exp, cr, scen, tag = m.groups()
        cr = int(cr); exp = int(exp)

        # Build factory + kwargs (mirrors main.py:load_model)
        if model_id == 'v1':
            factory = getattr(M, 'dcrnet')
            kwargs = dict(reduction=cr, expansion=exp)
        elif model_id in ('crnet', 'clnet', 'transnet'):
            factory = getattr(M, model_id)
            kwargs = dict(reduction=cr)
        else:
            factory = getattr(M, f'dcrnet_{model_id}')
            kwargs = dict(reduction=cr, expansion=exp)
            sig = inspect.signature(factory)
            if 'h' in sig.parameters: kwargs['h'] = 32
            if 'w' in sig.parameters: kwargs['w'] = 32
            # v9 unified flags
            if 'v12r' in tag and 'hybrid_decoder' in sig.parameters:
                kwargs.update(dict(
                    r_enc=512, refine_width=2, refine_K=1,
                    use_film=False, complex_encoder=True, enc_fuse_mlp=64,
                    hybrid_decoder=True, hybrid_direct_ranks=32, hybrid_extra_ranks=16,
                    hybrid_extra_d_emb=16, hybrid_gate_bias=-2.0,
                    hybrid_alpha_init=1e-2,
                ))
            # v5 sweep flags
            elif model_id == 'v5' and 'r_enc' in sig.parameters:
                kwargs.update(dict(r_enc=512, ranks=16))

        try:
            model = factory(**kwargs).to(device).eval()
        except Exception as e:
            print(f'  {base}: build err {e}')
            continue

        ckpt = torch.load(p, map_location=device)
        sd = ckpt['state_dict'] if isinstance(ckpt, dict) and 'state_dict' in ckpt else ckpt
        try:
            missing, unexp = model.load_state_dict(sd, strict=False)
        except Exception as e:
            print(f'  {base}: load err {e}')
            continue

        # Run inference
        nmse_list = []
        with torch.no_grad():
            for s in range(0, n_test, args.batch_size):
                xb = x_te[s:s + args.batch_size]
                fwd_sig = inspect.signature(model.forward).parameters
                if 'clamp' in fwd_sig:
                    pred = model(xb, clamp=True)
                else:
                    pred = model(xb)
                gt_c = xb - 0.5
                pred_c = pred - 0.5
                power_gt = (gt_c[:, 0] ** 2 + gt_c[:, 1] ** 2).sum(dim=[1, 2])
                diff = gt_c - pred_c
                mse = (diff[:, 0] ** 2 + diff[:, 1] ** 2).sum(dim=[1, 2])
                nmse_per_sample = mse / power_gt.clamp(min=1e-20)
                nmse_list.append(nmse_per_sample)
        nmse_all = torch.cat(nmse_list)
        nmse_db = 10 * torch.log10(nmse_all.mean()).item()
        results.append((model_id, cr, tag, nmse_db))
        print(f'  {model_id:8s} cr={cr:2d}  tag={tag:30s}  NMSE_BS18 = {nmse_db:+8.3f} dB')

    # ----- summary table -----
    print()
    print('=' * 78)
    print('Cross-BS NMSE (train: BS 16, test: BS 18) -- 10K NLoS UEs each')
    print('=' * 78)
    rows = {}
    for model_id, cr, tag, nmse in results:
        rows.setdefault(model_id, {})[cr] = (nmse, tag)
    # Sort models for nice output
    ordered = ['v1', 'v5', 'v9', 'crnet', 'clnet', 'transnet']
    print(f'{"model":12s} {"cr=4":>14s} {"cr=8":>14s} {"cr=16":>14s} {"cr=32":>14s}')
    for mid in ordered:
        if mid not in rows: continue
        vals = []
        for cr in (4, 8, 16, 32):
            v = rows[mid].get(cr)
            vals.append(f'{v[0]:+8.2f} dB' if v else '       -    ')
        print(f'{mid:12s} {vals[0]:>14s} {vals[1]:>14s} {vals[2]:>14s} {vals[3]:>14s}')


if __name__ == '__main__':
    main()
